//! The threshold calculation partitions of the psychoacoustic model
//! (clause C.1.4, step 5), by sampling frequency and FFT: Tables C.1 to
//! C.24, transcribed as printed.
//!
//! Each row gives a partition `b` by its position in its table: its lowest
//! and highest FFT lines, `w_low(b)` and `w_high(b)`, its width in lines,
//! its median Bark value `bval(b)`, and its threshold in quiet `qsthr(b)`
//! in dB.

use crate::sampling_frequency::SamplingFrequency;
use crate::scalefactor_bands::Transform;

/// A threshold calculation partition: a row of Tables C.1 to C.24.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Row {
    pub w_low: u16,
    pub w_high: u16,
    /// The width as printed: `w_high - w_low + 1` but in one row (see
    /// [`table`]).
    pub width: u16,
    pub bval: f64,
    pub qsthr: f64,
}

const fn row(w_low: u16, w_high: u16, width: u16, bval: f64, qsthr: f64) -> Row {
    Row {
        w_low,
        w_high,
        width,
        bval,
        qsthr,
    }
}

impl Row {
    /// The partition's FFT lines, `w_low(b)` to `w_high(b)`.
    pub fn lines(&self) -> std::ops::Range<usize> {
        usize::from(self.w_low)..usize::from(self.w_high) + 1
    }
}

/// The partitions of the long FFT, whose lines are those of a long window,
/// or of the short FFT, those of a short window, at `sampling_frequency`.
///
/// Spec reading: the last row of Table C.18 (48 kHz, short FFT) prints a
/// width of 1 for its lines 126 to 127, which are 2. The lines are taken,
/// as they cover the FFT's lines with those of the rows before, as the
/// other tables' do; the width column is not used.
pub fn table(sampling_frequency: SamplingFrequency, transform: Transform) -> &'static [Row] {
    use SamplingFrequency::*;
    match (transform, sampling_frequency) {
        (Transform::Long, Hz8000) => &LONG_8000,
        (Transform::Long, Hz11025) => &LONG_11025,
        (Transform::Long, Hz12000) => &LONG_12000,
        (Transform::Long, Hz16000) => &LONG_16000,
        (Transform::Long, Hz22050) => &LONG_22050,
        (Transform::Long, Hz24000) => &LONG_24000,
        (Transform::Long, Hz32000) => &LONG_32000,
        (Transform::Long, Hz44100) => &LONG_44100,
        (Transform::Long, Hz48000) => &LONG_48000,
        (Transform::Long, Hz64000) => &LONG_64000,
        (Transform::Long, Hz88200) => &LONG_88200,
        (Transform::Long, Hz96000) => &LONG_96000,
        (Transform::Short, Hz8000) => &SHORT_8000,
        (Transform::Short, Hz11025) => &SHORT_11025,
        (Transform::Short, Hz12000) => &SHORT_12000,
        (Transform::Short, Hz16000) => &SHORT_16000,
        (Transform::Short, Hz22050) => &SHORT_22050,
        (Transform::Short, Hz24000) => &SHORT_24000,
        (Transform::Short, Hz32000) => &SHORT_32000,
        (Transform::Short, Hz44100) => &SHORT_44100,
        (Transform::Short, Hz48000) => &SHORT_48000,
        (Transform::Short, Hz64000) => &SHORT_64000,
        (Transform::Short, Hz88200) => &SHORT_88200,
        (Transform::Short, Hz96000) => &SHORT_96000,
    }
}

