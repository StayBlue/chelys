#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn partitions_cover_each_fft_in_order() {
        for fs in SamplingFrequency::ALL {
            for transform in [Transform::Long, Transform::Short] {
                let rows = table(fs, transform);
                assert_eq!(rows[0].w_low, 0, "{fs:?} {transform:?}");
                assert_eq!(
                    usize::from(rows[rows.len() - 1].w_high) + 1,
                    transform.lines(),
                    "{fs:?} {transform:?}"
                );
                for pair in rows.windows(2) {
                    assert_eq!(pair[1].w_low, pair[0].w_high + 1, "{fs:?} {transform:?}");
                    // The Bark scale rises, but for the top partitions of
                    // the higher sampling frequencies, which all print 24.
                    assert!(
                        pair[1].bval > pair[0].bval || pair[1].bval == 24.0,
                        "{fs:?} {transform:?}"
                    );
                }
            }
        }
    }

    #[test]
    fn widths_are_the_lines_but_in_one_misprint() {
        for fs in SamplingFrequency::ALL {
            for transform in [Transform::Long, Transform::Short] {
                for (b, row) in table(fs, transform).iter().enumerate() {
                    let misprint =
                        (fs, transform, b) == (SamplingFrequency::Hz48000, Transform::Short, 41);
                    assert_eq!(
                        usize::from(row.width) == row.lines().len(),
                        !misprint,
                        "{fs:?} {transform:?} {b}"
                    );
                }
            }
        }
    }

    #[test]
    fn row_counts_follow_the_tables() {
        use SamplingFrequency::*;
        let counts = [
            (Hz8000, 52, 40),
            (Hz11025, 56, 47),
            (Hz12000, 57, 48),
            (Hz16000, 60, 47),
            (Hz22050, 63, 46),
            (Hz24000, 66, 46),
            (Hz32000, 66, 44),
            (Hz44100, 70, 42),
            (Hz48000, 69, 42),
            (Hz64000, 67, 39),
            (Hz88200, 72, 37),
            (Hz96000, 71, 36),
        ];
        for (fs, long, short) in counts {
            assert_eq!(table(fs, Transform::Long).len(), long, "{fs:?}");
            assert_eq!(table(fs, Transform::Short).len(), short, "{fs:?}");
        }
    }
}
