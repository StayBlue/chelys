//! How often chelys's encoder codes each entry of its residue's and floor's
//! books, from which their codeword lengths are made: the lengths of a
//! Huffman code for these counts, each raised by [`UNSEEN`], so that the
//! codes are near the shortest for chelys's own streams.
//!
//! The specification describes no encoder, and its codebooks are chelys's
//! own. The counts are those of the encoder's streams of the 51 tracks of
//! the tuning set of chelys's corpus (see `chelys_core::quality`), at 44.1
//! kHz in stereo, at noise offsets of -8, -5 and -2 dB, about 150, 108 and
//! 82 kbit/s, summed, short blocks and long ones together, as they share
//! the books. Coded with counts so taken rather than with the earlier
//! models of each book, in which the magnitude of each value fell off
//! exponentially, the streams of long blocks alone took 6.3% fewer bytes
//! at 0 dB, 8.6% at 3 dB and 12.6% at 6 dB, the offsets the counts were
//! taken at then, before the model weighed each band's noise (see
//! `psychoacoustic::BAND_EXPONENT`), which lowered the offsets of the same
//! bitrates by about 7 dB.
//!
//! Stereo streams are coupled, and code their residues with the books of
//! [`COUPLED`], whose counts, and the floor's, are taken so. The books of
//! [`UNCOUPLED`], which code the channels of every other stream each on its
//! own, are counted from the same streams coded so, each channel on its
//! own.
//!
//! The counts follow the encoder: they are to be taken again as it
//! changes what it codes.

/// What each count is raised by, so that an entry never coded in the
/// streams counted still has a codeword: half a coding.
const UNSEEN: f64 = 0.5;

/// The weights of a book's entries for [`huffman_lengths`], from `counts`.
///
/// [`huffman_lengths`]: super::codebook::huffman_lengths
pub fn weights(counts: &[u32]) -> Vec<f64> {
    counts
        .iter()
        .map(|&count| f64::from(count) + UNSEEN)
        .collect()
}

